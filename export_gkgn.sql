-- Convert the ГКГН CSV into a DuckDB-friendly Parquet file.
--
-- Run from the repository root:
--   duckdb < export_gkgn.sql
--
-- The filter is intentionally an exclusion list.  ГКГН contains many
-- object-type variants, so a whitelist of lake-related types would discard
-- useful water objects that we have not identified yet.

