COPY (
  SELECT
    NULLIF(trim(trim(csv_gkgn_id, '"')), '') AS gkgn_id,
    NULLIF(trim(trim(csv_name, '"')), '') AS name,
    lower(trim(trim(csv_type, '"'))) AS object_type,
    NULLIF(trim(trim(csv_region, '"')), '') AS region,
    TRY_CAST(NULLIF(trim(trim(csv_lat, '"')), '') AS DOUBLE) AS latitude,
    TRY_CAST(NULLIF(trim(trim(csv_lon, '"')), '') AS DOUBLE) AS longitude
  FROM read_csv(
    'gkgn.csv',
    delim = ';',
    header = false,
    skip = 1,
    quote = '',
    parallel = false,
    columns = {
      'csv_gkgn_id': 'VARCHAR',
      'csv_name': 'VARCHAR',
      'csv_type': 'VARCHAR',
      'csv_region': 'VARCHAR',
      'csv_district': 'VARCHAR',
      'csv_lat': 'VARCHAR',
      'csv_lon': 'VARCHAR'
    },
    encoding = 'UTF-8'
  )
  WHERE NULLIF(trim(trim(csv_name, '"')), '') IS NOT NULL
    AND lower(trim(trim(csv_type, '"'))) NOT IN (
      SELECT type_name FROM excluded_object_types
    )
    -- Keep the exclusion strategy robust to inflected/plural variants.
    AND NOT regexp_matches(
      lower(trim(trim(csv_type, '"'))),
      '^(село|деревн|пос[её]л|хутор|город|станиц|аул|улус|район|округ|сельсовет|сельск.*(пос[её]л|террит)|сумон|железнодорожн.*\(нп\)|.*\(нп\)$|гора|горн|хреб|сопк|скал|холм|курган|перевал|овраг|балк|лог|ущел|долин|равнин|низмен|возвыш|плато|плоскогор|нагор|увал|яр|ледник|вулкан|лес|степ|тундр|пустош|песк|бархан|солончак|остров|архипелаг|полуостров|перешеек|мыс|коса|риф|банка|отмель|мель|берег|развалины|местность|поляна|просек|тропа|брод|проход|курортн.*пос[её]л|дачн.*пос[её]л|рабоч.*пос[её]л)'
    )
    AND region != 'Донецкая Народная Республика'
    AND region != 'Луганская Народная Республика'
    AND region != 'Запорожская область'
    AND region != 'Херсонская область'
) TO 'data/gkgn.parquet'
(FORMAT PARQUET, COMPRESSION ZSTD, ROW_GROUP_SIZE 10000);

-- Basic output check and a sample of retained types.
SELECT COUNT(*) AS exported_rows
FROM read_parquet('data/gkgn.parquet');

SELECT object_type, COUNT(*) AS rows
FROM read_parquet('data/gkgn.parquet')
GROUP BY object_type
ORDER BY rows DESC;
